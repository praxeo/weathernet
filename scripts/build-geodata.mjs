// Regenerates the small static geo tables the worker labels things with:
//   src/data/places.js  — US populated places (Natural Earth 10m, public domain)
//   src/data/radars.js  — WSR-88D sites (api.weather.gov/radar/stations)
// Run offline when they need refreshing:
//   NODE_USE_ENV_PROXY=1 node scripts/build-geodata.mjs
import { writeFileSync } from "node:fs";
import { inflateRawSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const UA = "WeatherNet/0.1 (build script)";

const STATES = {
  Alabama: "AL", Alaska: "AK", Arizona: "AZ", Arkansas: "AR", California: "CA", Colorado: "CO",
  Connecticut: "CT", Delaware: "DE", "District of Columbia": "DC", Florida: "FL", Georgia: "GA",
  Hawaii: "HI", Idaho: "ID", Illinois: "IL", Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY",
  Louisiana: "LA", Maine: "ME", Maryland: "MD", Massachusetts: "MA", Michigan: "MI", Minnesota: "MN",
  Mississippi: "MS", Missouri: "MO", Montana: "MT", Nebraska: "NE", Nevada: "NV", "New Hampshire": "NH",
  "New Jersey": "NJ", "New Mexico": "NM", "New York": "NY", "North Carolina": "NC", "North Dakota": "ND",
  Ohio: "OH", Oklahoma: "OK", Oregon: "OR", Pennsylvania: "PA", "Rhode Island": "RI",
  "South Carolina": "SC", "South Dakota": "SD", Tennessee: "TN", Texas: "TX", Utah: "UT", Vermont: "VT",
  Virginia: "VA", Washington: "WA", "West Virginia": "WV", Wisconsin: "WI", Wyoming: "WY",
};

async function getJSON(url) {
  const r = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/geo+json,application/json" } });
  if (!r.ok) throw new Error(`${r.status} on ${url}`);
  return r.json();
}

const r4 = (n) => Math.round(n * 1e4) / 1e4;

const ne = await getJSON(
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson",
);
const places = ne.features
  .map((f) => f.properties)
  .filter((p) => p.adm0_a3 === "USA" || p.adm0_a3 === "PRI")
  .map((p) => [p.nameascii || p.name, p.adm0_a3 === "PRI" ? "PR" : STATES[p.adm1name] || "", r4(p.latitude), r4(p.longitude), p.pop_max | 0])
  .filter((p) => p[1])
  .sort((a, b) => b[4] - a[4]);
writeFileSync(
  path.join(ROOT, "src/data/places.js"),
  "// US populated places: [name, state, lat, lon, population], largest first.\n" +
    "// Natural Earth 10m populated places (public domain). Generated by\n" +
    "// scripts/build-geodata.mjs — don't edit by hand.\n" +
    `export const PLACES = ${JSON.stringify(places)};\n`,
);

const rs = await getJSON("https://api.weather.gov/radar/stations?stationType=WSR-88D");
const radars = rs.features
  .map((f) => [f.properties.id, f.properties.name, r4(f.geometry.coordinates[1]), r4(f.geometry.coordinates[0])])
  .sort((a, b) => a[0].localeCompare(b[0]));
writeFileSync(
  path.join(ROOT, "src/data/radars.js"),
  "// WSR-88D (NEXRAD) sites: [id, name, lat, lon]. From api.weather.gov/radar/stations.\n" +
    "// Generated by scripts/build-geodata.mjs — don't edit by hand.\n" +
    `export const RADARS = ${JSON.stringify(radars)};\n`,
);

// County internal points (Census Gazetteer). NWS alerts without a polygon
// (zone-based: heat, blizzard, red flag…) still list their counties as SAME
// codes ("0" + FIPS), so these let the worker place them on a map.
const zip = Buffer.from(
  await (await fetch("https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_counties_national.zip")).arrayBuffer(),
);
const gaz = unzipFirst(zip).toString("utf8");
const rows = gaz.trim().split("\n").map((l) => l.split("\t").map((c) => c.trim()));
const head = rows.shift();
const col = (name) => head.indexOf(name);
const [iG, iLat, iLon] = [col("GEOID"), col("INTPTLAT"), col("INTPTLONG")];
const counties = {};
for (const r of rows) counties[r[iG]] = [Math.round(Number(r[iLat]) * 100) / 100, Math.round(Number(r[iLon]) * 100) / 100];
writeFileSync(
  path.join(ROOT, "src/data/counties.js"),
  "// County internal points by 5-digit FIPS: { fips: [lat, lon] }. Census 2024\n" +
    "// Gazetteer. Generated by scripts/build-geodata.mjs — don't edit by hand.\n" +
    `export const COUNTIES = ${JSON.stringify(counties)};\n`,
);

// Minimal reader for a single-entry .zip (local file header + raw deflate).
function unzipFirst(buf) {
  if (buf.readUInt32LE(0) !== 0x04034b50) throw new Error("not a zip");
  const method = buf.readUInt16LE(8);
  const size = buf.readUInt32LE(18);
  const start = 30 + buf.readUInt16LE(26) + buf.readUInt16LE(28);
  const data = buf.subarray(start, start + size);
  return method === 8 ? inflateRawSync(data) : data;
}

process.stdout.write(`places: ${places.length}, radars: ${radars.length}, counties: ${Object.keys(counties).length}\n`);
